import sys

# sys.stdin = open("input.txt", "r")  # 로컬 파일 테스트 시 주석 해제

"""
문제 구상
2N개의 정수가 주어지고, 이 숫자들을 N개씩 2개의 그룹으로 나눠야 한다.
첫 번째 그룹과 두 번째 그룹에 들어간 숫자들의 합을 각각 구한다.
두 그룹의 합의 차이가 가장 작아지도록 숫자를 나눴을 때 그 차이를 구한다.

로직 구상
1. N과 2N개의 정수를 입력받는다. # 리스트
2. 숫자를 첫 번째 그룹에 넣을지, 두 번째 그룹에 넣을지 선택한다. # 백트래킹(조합)
3. 첫 번째 그룹에 넣으면 더하고, 두 번째 그룹에 넣으면 빼면서 합의 차이를 계산한다.
4. 첫 번째 그룹에 들어간 숫자의 개수가 N개인지 확인한다.
5. 2N개의 숫자를 모두 확인했을 때 두 그룹의 합의 차이 중 최솟값을 구한다.
6. 숫자를 선택하기 전 상태로 돌아가 다른 경우도 확인한다. # 재귀, 백트래킹
7. 두 그룹의 합의 차이 중 최솟값을 출력한다.
"""

# 1. N과 2N개의 정수를 입력받는다. # 리스트
N = int(input())
arr = list(map(int, input().split()))

# 5-1. 가장 작은 차이를 구하기 위한 초기값 세팅
min_diff = 10 ** 9


# 2. 첫 번째 그룹에 넣을지 두 번째 그룹에 넣을지 선택하는 함수 # 백트래킹
# idx: 현재 확인하는 숫자의 인덱스
# count: 첫 번째 그룹에 선택한 숫자의 개수
# diff: 첫 번째 그룹의 합 - 두 번째 그룹의 합
def find_min(idx, count, diff):
    global min_diff

    # 4. 첫 번째 그룹에 정확히 N개를 선택해야 한다.
    # 4-1. 이미 N개를 초과하거나 남은 숫자를 모두 선택해도 N개가 안 되면 종료
    if count > N or count + (2 * N - idx) < N:
        return

    # 5. 2N개의 숫자를 모두 확인했을 때 최솟값을 갱신한다.
    if idx == 2 * N:
        if count == N:
            # 5-1. 두 그룹의 합의 차이이므로 절댓값을 구한다.
            if abs(diff) < min_diff:
                min_diff = abs(diff)
        return

    # 3. 현재 숫자를 첫 번째 그룹에 넣으면 합의 차이에 더한다.
    # 2-1. 첫 번째 그룹에 포함시키는 경우
    find_min(idx + 1, count + 1, diff + arr[idx])

    # 3-1. 현재 숫자를 두 번째 그룹에 넣으면 합의 차이에서 뺀다.
    # 6. 첫 번째 선택에서 돌아와 다른 경우를 확인한다. # 백트래킹
    find_min(idx + 1, count, diff - arr[idx])


# 2-2. 첫 번째 숫자부터 두 그룹에 나누는 모든 경우 확인
find_min(0, 0, 0)

# 7. 두 그룹의 합의 차이 중 최솟값 출력
print(min_diff)
